// Generate the complete D3D9 COM forwarding surface from the SDK declarations.
// Keeping this mechanical avoids handwritten omissions in the 119-method device.
import fs from 'node:fs';
const header = fs.readFileSync(process.argv[2], 'utf8');
const definitions = [...header.matchAll(/DECLARE_INTERFACE_IID_\((IDirect3D\w+),\s*(\w+),[^\n]+\)\s*\{([\s\S]*?)\n\};/g)];
let result = '// Generated by tools/generate-proxies.mjs. Do not edit individual forwarding methods.\n#include "proxy.hpp"\n#include "water.hpp"\n#include "depth_policy.hpp"\n';
let factories = '';
for (const [,type,parent,body] of definitions) {
  const device = /^IDirect3DDevice9/.test(type), root = /^IDirect3D9/.test(type), swap = /^IDirect3DSwapChain9/.test(type);
  const methods = [...body.matchAll(/STDMETHOD(?:_\(\s*([^,]+),\s*(\w+)\)|\(\s*(\w+)\))\(THIS(_\s*([\s\S]*?))?\)\s*PURE;/g)];
  if (methods.length < 3) throw new Error(`No methods: ${type}`);
  result += `\nclass Proxy_${type} final : public ${type}, public ProxyLife {\n    ${type}* real_;\npublic:\n    Proxy_${type}(${type}* p, IUnknown* owner) : ProxyLife(p, owner), real_(p) { registerSelf(this); ${device ? 'runtime_ = std::make_unique<Runtime>(p);' : ''} }\n`;
  for (const m of methods) {
    const ret = m[1]?.trim() || 'HRESULT', name = m[2] || m[3];
    let args = (m[5] || '').replace(/\s+/g,' ').trim();
    const params = args ? args.split(',').map((s,i)=> {
      s=s.trim(); return /^\w+$/.test(s) || /\*$/.test(s) ? `${s} arg${i}` : s;
    }) : [];
    args = params.join(', ');
    const names = params.map(p=>p.match(/(\w+)\s*(?:\[[^\]]*\])?$/)?.[1]);
    if (names.some(n=>!n)) throw new Error(`Parameter parse: ${type} ${name} ${args}`);
    let callArgs = params.map((p,i)=>/\bIDirect3D\w+\s*\*\s*\w+$/.test(p) ? `Unwrap(${names[i]})` : names[i]);
    let before = '', after = '';
    if (device && name === 'CheckResourceResidency') {
      before += `std::vector<IDirect3DResource9*> raw; if (${names[0]}) { raw.reserve(${names[1]}); for (UINT i=0;i<${names[1]};++i) raw.push_back(Unwrap(${names[0]}[i])); } `;
      callArgs[0] = `${names[0]} ? raw.data() : nullptr`;
    }
    let call = `real_->${name}(${callArgs.join(', ')})`;
    if((root && (name==='CreateDevice'||name==='CreateDeviceEx')) || (device && (name==='Reset'||name==='ResetEx'))) {
      const ppIndex=root?4:0;
      const adjustedArgs=[...callArgs];adjustedArgs[ppIndex]='fenbDepthParameters';
      const owner=root?`real_,${names[0]},${names[1]}`:'real_';
      call=device?`runtime_->resetPresentation(${names[ppIndex]},[&](D3DPRESENT_PARAMETERS* fenbDepthParameters){return real_->${name}(${adjustedArgs.join(', ')});})`:`WithConfiguredDepth(${owner},${names[ppIndex]},[&](D3DPRESENT_PARAMETERS* fenbDepthParameters){return real_->${name}(${adjustedArgs.join(', ')});})`;
      if(root) before+=`const auto fenbNative = ${names[ppIndex]} ? *${names[ppIndex]} : D3DPRESENT_PARAMETERS{}; `;
    }
    let code;
    if (name === 'QueryInterface') code = `return query(${names.join(', ')});`;
    else if (name === 'AddRef') code = 'return addRef();';
    else if (name === 'Release') code = 'return release();';
    else {
      if(device && ['DrawPrimitive','DrawIndexedPrimitive','DrawPrimitiveUP','DrawIndexedPrimitiveUP'].includes(name)) {
        const indexed=name.includes('Indexed'), up=name.endsWith('UP');
        const count = name==='DrawPrimitive'?names[2]:name==='DrawIndexedPrimitive'?names[5]:name==='DrawPrimitiveUP'?names[1]:names[3];
        const vertices = indexed?names[name==='DrawIndexedPrimitive'?3:2]:'0';
        const stride = up?names.at(-1):'0';
        const data = up?names[name==='DrawPrimitiveUP'?2:6]:'nullptr';
        const first = name==='DrawPrimitive'?names[1]:'0';
        before+=`if (${count}) runtime_->beforeDraw(${count},${vertices}); `;
        if(name==='DrawPrimitive') before+=`if (${count}) runtime_->environmentDraw(${names[0]},${names[1]},${count});`;
        before=before.trimEnd()+`\n#ifdef FENB_DIAGNOSTICS\n        runtime_->captureDraw("${name}",${names[0]},${count},${vertices},${stride},${data},${first});\n#endif\n        `;
        const geometry=name==='DrawPrimitive'?`{${names[0]},${names[1]},${count}}`:
          name==='DrawIndexedPrimitive'?`{${names[0]},${names[4]},${count},${names[2]},${names[3]},${names[1]},true}`:'{}';
        before+=`if (${count} && (runtime_->settings.localLighting || runtime_->settings.surfaceReflections)) runtime_->emitterDraw([&](){return ${call};},${geometry}); `;
        before+=`if (${count}) runtime_->beforeWaterDraw(${stride},[&](){return ${call};}); `;
        after+=`runtime_->afterWaterDraw(${up},${up&&indexed}); `;
      }
      if(type==='IDirect3DTexture9'&&name==='UnlockRect')after+='if(SUCCEEDED(hr)) InvalidateWaterTag(real_); ';
      if(['Lock','LockRect','LockBox'].includes(name) && !device && !root && !swap)
        before+=`if (!(${names.at(-1)} & D3DLOCK_READONLY)) { auto* rt=RuntimeFor(owner_); if(rt) rt->surfaceBarrier(); } `;
      if(name==='GetDC' && type==='IDirect3DSurface9')before+='auto* rt=RuntimeFor(owner_); if(rt) rt->surfaceBarrier(); ';
      if(device && ['UpdateSurface','UpdateTexture','ProcessVertices','ColorFill','StretchRect'].includes(name))before+='runtime_->surfaceBarrier(); ';
      if(type==='IDirect3DSurface9'&&name==='UnlockRect')after+='if(SUCCEEDED(hr)) InvalidateWaterSurface(real_); ';
      if(device&&name==='UpdateSurface')after+=`if(SUCCEEDED(hr)) InvalidateWaterSurface(Unwrap(${names[2]})); `;
      if(device&&name==='UpdateTexture')after+=`if(SUCCEEDED(hr)) InvalidateWaterTag(Unwrap(${names[1]})); `;
      if(device && name==='SetFVF') after+=`if(SUCCEEDED(hr)) runtime_->drawFVF(${names[0]}); `;
      if(device && name==='SetVertexShader') after+=`if(SUCCEEDED(hr)) runtime_->drawShader(${names[0]} != nullptr); `;
      if(device && name==='SetVertexDeclaration') after+='if(SUCCEEDED(hr)) runtime_->invalidateDrawState(); ';
      if(device && name==='SetRenderTarget') after+=`if(SUCCEEDED(hr)) runtime_->drawTarget(${names[0]},Unwrap(${names[1]})); `;
      if(type==='IDirect3DStateBlock9' && name==='Apply') after+='if(SUCCEEDED(hr)) { auto* rt=RuntimeFor(owner_); if(rt) rt->invalidateDrawState(); } ';
      if (device && (name === 'Reset' || name === 'ResetEx')) { before += 'runtime_->beforeReset(); '; after += 'runtime_->afterReset(hr); '; }
      if ((device || swap) && (name === 'Present' || name === 'PresentEx')) {
        const runtime = device ? 'runtime_.get()' : 'RuntimeFor(owner_)';
        before += `auto* rt = ${runtime}; if (rt) rt->beforePresent(${swap ? 'real_' : 'nullptr'}, ${swap || name === 'PresentEx' ? names.at(-1) : '0'}, ${names[2]}); `;
        after += `if (rt) { rt->afterPresent(hr); hr = rt->presentationResult(hr, ${swap?'real_':'nullptr'}, ${swap || name === 'PresentEx' ? names.at(-1) : '0'}); } `;
      }
      if (device && name === 'TestCooperativeLevel') after += 'hr = runtime_->cooperativeResult(hr); ';
      if (device && name === 'BeginScene') after += 'if (SUCCEEDED(hr)) runtime_->scene(true); ';
      if (device && name === 'EndScene') after += 'if (SUCCEEDED(hr)) runtime_->scene(false); ';
      if (device && name === 'Clear') after += `if (SUCCEEDED(hr)) runtime_->targetCleared(${names[2]},${names[0]}); `;
      if (ret === 'HRESULT') {
        for (let i=0;i<params.length;i++) {
          if (/\bIDirect3D\w+\s*\*\s*\*\s*\w+$/.test(params[i]) && name !== 'CheckResourceResidency')
            after += `if (SUCCEEDED(hr)) Adopt(${names[i]}, ${device || root ? 'self_' : 'owner_'}); `;
        }
        if (name === 'GetContainer') after += `if (SUCCEEDED(hr) && ${names[1]}) WrapObject(${names[0]}, ${names[1]}, owner_); `;
        if(root && (name==='CreateDevice'||name==='CreateDeviceEx')) after+=`if (SUCCEEDED(hr) && ${names.at(-1)} && *${names.at(-1)}) { auto* rt=RuntimeFor(*${names.at(-1)}); if(rt) rt->nativePresentation(fenbNative); } `;
        code = `${before}auto hr = ${call}; ${after}return hr;`;
      } else code = before + `return ${call};`;
    }
    result += `    ${ret} STDMETHODCALLTYPE ${name}(${args}) noexcept override { ${code} }\n`;
  }
  result += '};\n';
  factories += `    if (iid == __uuidof(${type})) return new Proxy_${type}(static_cast<${type}*>(object), owner);\n`;
}
result += `\nProxyLife* MakeProxy(REFIID iid, void* object, IUnknown* owner) {\n${factories}    return nullptr;\n}\n`;
fs.mkdirSync('src/generated',{recursive:true});
fs.writeFileSync('src/generated/proxies.cpp', result);
console.log(`Generated ${definitions.length} interfaces`);
