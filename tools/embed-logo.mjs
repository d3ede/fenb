import fs from 'node:fs';

const bytes = fs.readFileSync('assets/branding/header-preview/symbol.bgra');
const width = bytes.readUInt32LE(0), height = bytes.readUInt32LE(4);
if (!width || !height || width > 512 || height > 256 || bytes.length !== 8 + width * height * 4)
  throw new Error('Invalid header symbol BGRA asset');
const lines = [];
for (let offset = 8; offset < bytes.length; offset += 32) {
  const words = [];
  for (let p = offset; p < Math.min(offset + 32, bytes.length); p += 4)
    words.push('0x' + bytes.readUInt32LE(p).toString(16).padStart(8, '0') + 'u');
  lines.push('    ' + words.join(', ') + ',');
}
fs.mkdirSync('src/generated', { recursive: true });
fs.writeFileSync('src/generated/ui_logo.hpp',
  `// Approved Refined Bloom symbol. Generated by tools/embed-logo.mjs.\n#pragma once\n#include <cstdint>\ninline constexpr unsigned UI_LOGO_WIDTH = ${width};\ninline constexpr unsigned UI_LOGO_HEIGHT = ${height};\ninline constexpr std::uint32_t UI_LOGO_BGRA[] = {\n${lines.join('\n')}\n};\n`);
