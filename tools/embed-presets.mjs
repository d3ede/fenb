// Compile image profiles into the DLL. General/environment settings never belong to a look.
import fs from 'node:fs';
const read = file => fs.readFileSync(new URL('../'+file, import.meta.url), 'utf8');
const members = new Map();
for (const [,type,key,member] of read('src/settings.cpp').matchAll(/READ_(BOOL|FLOAT)\(\s*"([^"]+)",\s*(\w+)\)/g))
  members.set(key, {member,type});
for (const [,type,member,key] of read('src/scene_settings.inc').matchAll(/SCENE_(BOOL|FLOAT)\(\d+,\s*(\w+),\s*"([^"]+)"/g))
  members.set(key,{member,type});
for (const [key,member] of Object.entries({bloom_scale:'bloomScale',water_ssr_quality:'waterSSRQuality',water_caustic_scale:'waterCausticScale'}))
  members.set(key,{member,type:'INT'});
const base = new Map();
let section='';
for(const line of read('config/FENB.ini').split(/\r?\n/)) {
  if(line.startsWith('['))section=line.slice(1,line.indexOf(']'));
  if(!['Bloom','Color','WaterFX','SceneFX'].includes(section))continue;
  const match=line.match(/^([\w_]+)=([^;]+)/);
  if(!match || match[1]==='msaa_samples')continue;
  if(!members.has(match[1]))throw Error('Unmapped image setting: '+match[1]);
  base.set(match[1],Number(match[2]));
}
const profiles=JSON.parse(read('config/builtins.json'));
if(!profiles.length || profiles[0].name!=='Default' || Object.keys(profiles[0].overrides).length)throw Error('Default must inherit the shipped image settings');
const assignment=(key,value)=>{
  if(!base.has(key)||!Number.isFinite(value))throw Error('Invalid image override: '+key);
  const {member,type}=members.get(key);
  return `    s.${member} = ${type==='BOOL'?(value?'true':'false'):type==='INT'?String(value):value.toFixed(6)+'f'};\n`;
};
let out='// Generated by tools/embed-presets.mjs from config/FENB.ini and config/builtins.json.\n#pragma once\n';
out+='static_assert(BuiltInPresetCount == '+profiles.length+');\ninline void ApplyBuiltInVisuals(Settings &s, int index) {\n';
for(const [key,value] of base)out+=assignment(key,value);
out+='    switch(index) {\n';
for(let i=1;i<profiles.length;++i) {
  out+=`    case ${i}: // ${profiles[i].name}\n`;
  for(const [key,value] of Object.entries(profiles[i].overrides))out+=assignment(key,value);
  out+='        break;\n';
}
out+='    default: break;\n    }\n}\n';
fs.writeFileSync(new URL('../src/generated/presets.hpp',import.meta.url),out);
