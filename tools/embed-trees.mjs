import fs from 'node:fs';
const manifest=JSON.parse(fs.readFileSync('tools/trees.json','utf8'));
if(manifest.schema!==1||!manifest.sources.length)throw Error('Invalid tree manifest');
const paths=[...new Set(manifest.sources.flatMap(source=>[source.asset,source.alternateAsset].filter(Boolean)))].sort(),data=[],assets=[];
for(const file of paths){
 const b=fs.readFileSync(file),u=p=>b.readUInt32LE(p),four=b.toString('ascii',84,88);
 if(b.toString('ascii',0,4)!=='DDS '||u(4)!==124||!['DXT1','DXT5'].includes(four))throw Error('Invalid tree DDS '+file);
 const width=u(16),height=u(12),levels=u(28),offset=data.length;
 let w=width,h=height,expected=128;
 for(let i=0;i<levels;i++){expected+=Math.max(1,Math.ceil(w/4))*Math.max(1,Math.ceil(h/4))*(four==='DXT1'?8:16);w=Math.max(1,w>>1);h=Math.max(1,h>>1);}
 if(!width||!height||width>512||height>512||levels!==1+Math.floor(Math.log2(Math.max(width,height)))||w!==1||h!==1||expected!==b.length)throw Error('Invalid tree mip chain '+file);
 for(const byte of b.subarray(128))data.push(byte);assets.push({width,height,levels,format:four==='DXT1'?0x31545844:0x35545844,offset,size:b.length-128});
}
const identities=new Map(),alternates=new Map(),kinds=new Map();
for(const source of manifest.sources){
 const asset=paths.indexOf(source.asset);
 const alternate=source.alternateAsset?paths.indexOf(source.alternateAsset):asset;
 for(const index of [asset,alternate]){
  if(source.width!==assets[index]?.width||source.height!==assets[index]?.height)throw Error('Tree dimensions changed: '+source.file);
 }
 if(source.alternateAsset&&(alternate===asset||assets[asset].format!==assets[alternate].format))throw Error('Invalid alternate tree asset: '+source.file);
 if(alternates.has(asset)&&alternates.get(asset)!==alternate)throw Error('Inconsistent variants for shared tree asset: '+source.file);
 alternates.set(asset,alternate);
 const kind=source.kind??'bark';
 if(!['bark','foliage'].includes(kind))throw Error('Invalid tree material kind: '+source.file);
 for(const index of [asset,alternate]){
  if(kinds.has(index)&&kinds.get(index)!==kind)throw Error('Inconsistent tree material kinds: '+source.file);
  kinds.set(index,kind);
 }
 for(const hash of [source.uploadSha256,source.decodedSha256]){
  if(!/^[0-9a-f]{64}$/.test(hash))throw Error('Invalid tree identity');
  if(identities.has(hash)&&identities.get(hash)!==asset)throw Error('Ambiguous tree source');identities.set(hash,asset);
 }
}
let out='// Generated by tools/embed-trees.mjs; do not edit.\n#pragma once\n';
out+='struct TreeAsset { unsigned width,height,levels,format,offset,size,alternate; bool foliage; };\ninline constexpr TreeAsset TreeAssets[] = {\n';
for(const [index,a] of assets.entries())out+=`{${a.width},${a.height},${a.levels},${a.format}u,${a.offset},${a.size},${alternates.get(index)??index},${kinds.get(index)==='foliage'}},\n`;
out+='};\nstruct TreeIdentity { unsigned char hash[32]; unsigned asset; };\ninline constexpr TreeIdentity TreeIdentities[] = {\n';
for(const [hash,asset]of[...identities].sort((a,b)=>a[0].localeCompare(b[0])))out+=`{{${hash.match(/../g).map(v=>'0x'+v).join(',')}},${asset}},\n`;
out+='};\ninline constexpr unsigned char TreeTextureData[] = {\n';
for(let i=0;i<data.length;i+=32)out+=data.slice(i,i+32).map(v=>'0x'+v.toString(16).padStart(2,'0')).join(',')+',\n';
out+='};\n';fs.writeFileSync('src/generated/trees.hpp',out);
console.log(`Embedded ${assets.length} tree textures (${data.length} bytes), ${identities.size} source identities.`);
