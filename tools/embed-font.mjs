import fs from 'node:fs';
const bytes=fs.readFileSync('assets/fonts/FENB-UI.ttf');
const lines=[];for(let i=0;i<bytes.length;i+=24)lines.push('  '+[...bytes.subarray(i,i+24)].join(',')+',');
fs.mkdirSync('src/generated',{recursive:true});
fs.writeFileSync('src/generated/ui_font.hpp',`// Subset of Inter, SIL OFL 1.1. See assets/fonts/OFL.txt. Generated by tools/embed-font.mjs.\n#pragma once\ninline constexpr unsigned char UI_FONT[] = {\n${lines.join('\n')}\n};\n`);
